import { GemType, GemColor, DamageType } from "../models/types";

export interface GemData {
  id: string;
  name: string;
  type: GemType;
  color: GemColor;
  requiredLevel: number;
  description: string;
  limitedDrop?: boolean;        // 限定掉落，不可通过NPC购买

  // 主动宝石属性
  active?: {
    baseDamage: number;
    tags: string[];
    damageType: DamageType;
    manaCost: number;
    castTime: number;
    levelScaling: "per_level" | "flat";
    flatDamagePerLevel?: number;
  };

  // 辅助宝石属性
  support?: {
    multiplier?: number;           // 伤害乘率 (more)
    addedTags?: string[];          // 添加的标签（同时也是生效所需的标签）
    specialEffect?: string;        // 特殊效果ID
    addedStats?: { stat: string; value: number }[];  // 额外属性
  };
}

