// 获取所有宝石
export const ALL_GEMS: GemData[] = [...ACTIVE_GEMS, ...SUPPORT_GEMS];

// 按ID查找宝石
export function getGemById(id: string): GemData | undefined {
  return ALL_GEMS.find((g) => g.id === id);
}

// 按类型获取宝石
export function getGemsByType(type: GemType): GemData[] {
  return ALL_GEMS.filter((g) => g.type === type);
}

// 按颜色获取宝石
export function getGemsByColor(color: GemColor): GemData[] {
  return ALL_GEMS.filter((g) => g.color === color);
}
